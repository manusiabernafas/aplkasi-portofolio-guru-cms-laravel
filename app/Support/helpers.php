/** Alamat gambar unggahan (public/uploads) atau gambar bawaan. */
function gambar(?string $path, string $cadangan = 'img/sampul.svg'): string
{
    return asset($path ? 'uploads/' . $path : $cadangan);
}

/** Markdown aman: HTML mentah dibuang, tautan berbahaya ditolak. */
function md(?string $teks): string
{
    return Str::markdown((string) $teks, ['html_input' => 'strip', 'allow_unsafe_links' => false]);
}

function situs(string $k): string
{
    return Situs::get($k);
}

function tgl(?string $tgl): string
{
    if (! $tgl) {
        return '-';
    }
    $b = [1 => 'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni', 'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember'];
    $t = strtotime($tgl);
    return date('j', $t) . ' ' . $b[(int) date('n', $t)] . ' ' . date('Y', $t);
}

